export function generateEndlessCase(seed = 1024) {
  const numericSeed = hashSeed(seed);
  const rand = createMulberry32(numericSeed);

  // Exclude opaque pyrite as mystery truth so optical transmitted-light benches are always decisive
  const candidates = MINERAL_CODEX.filter((m) => !m.isOpaque);
  const truth = candidates[Math.floor(rand() * candidates.length)];

  // Score decoys: mix 1-2 close RI/SG neighbors + 1 contrasting optic class for a fair, fun puzzle
  const others = candidates.filter((m) => m.id !== truth.id);
  const scored = others
    .map((m) => {
      const riDiff = Math.abs(m.indices[1] - truth.indices[1]);
      const sgDiff = Math.abs(m.sg - truth.sg);
      const classBonus = m.opticClass !== truth.opticClass ? 0.15 : 0;
      const jitter = rand() * 0.35;
      return { m, score: riDiff * 1.4 + sgDiff * 0.25 + classBonus + jitter };
    })
    .sort((a, b) => a.score - b.score);

  const pickedDecoys = [scored[0].m.id, scored[1].m.id, scored[3 + Math.floor(rand() * 4)].m.id];
  const rawSuspects = [truth.id, ...pickedDecoys];
  // Deterministic Fisher-Yates shuffle
  for (let i = rawSuspects.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [rawSuspects[i], rawSuspects[j]] = [rawSuspects[j], rawSuspects[i]];
  }

  const [clientZh, clientRoleZh] = ENDLESS_CLIENTS[Math.floor(rand() * ENDLESS_CLIENTS.length)];
  const adj = ENDLESS_ADJECTIVES[Math.floor(rand() * ENDLESS_ADJECTIVES.length)];
  const serial = String(numericSeed % 10000).padStart(4, '0');

  return {
    id: `endless_${numericSeed}`,
    caseCode: `ENDLESS #${serial}`,
    seed: numericSeed,
    isEndless: true,
    difficulty: 2 + (numericSeed % 2),
    xpReward: 150,
    titleZh: `${adj}未知原石 #${serial}`,
    clientZh,
    clientRoleZh,
    briefZh: `收到一枚未贴标签的天然透明原石（晶系与折射率未知）。请在 4 项嫌疑矿物中运用折光仪、锥光镜、二色镜与比重天平锁定真身！`,
    storyIntro: '自由无尽委托：综合光性类别、正负光性、RI 阴影界、二色镜多色性（及红/蓝宝石晶习双晶）与静水 SG 进行交叉排他验证。',
    truthMineralId: truth.id,
    suspectIds: rawSuspects,
    recommendedTools: ['refractometer', 'conoscope', 'dichroscope', 'sg'],
    decisiveClueZh: `${truth.opticLabel} · ${truth.systemZh}（${truth.diagnosticTip}）`,
    debriefZh: `盲测命中！标本 #${serial} 真身为【${truth.nameZh} (${truth.nameEn})】：${truth.opticLabel}，SG ${truth.sg.toFixed(2)}。`,
  };
}

