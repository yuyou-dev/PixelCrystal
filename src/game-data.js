const SYSTEM_BY_ID = new Map(CRYSTAL_SYSTEMS.map((s) => [s.id, s]));

function formatRiText(indices, className) {
  if (className === 'isotropic') {
    return indices[0].toFixed(3);
  }
  const lo = Math.min(...indices).toFixed(3);
  const hi = Math.max(...indices).toFixed(3);
  return `${lo}–${hi}`;
}

function makeCodexEntry(raw, idx) {
  const mat = getMaterial(raw.id);
  const oa = opticAxisInfo(raw.id);
  const sys = SYSTEM_BY_ID.get(raw.systemId) || CRYSTAL_SYSTEMS[0];
  const riText = raw.riOverride || formatRiText(mat.indices, mat.className);
  const opticLabel = raw.isOpaque
    ? `金属反光不透明 (R≈54.5%) · SG ${mat.sg.toFixed(2)}`
    : `${oa.signLabelZh} · RI ${riText} · Δn ${oa.deltaN.toFixed(3)}`;

  return Object.freeze({
    codexNo: String(idx + 1).padStart(2, '0'),
    id: raw.id,
    materialId: raw.id,
    nameZh: raw.nameZh,
    nameEn: raw.nameEn,
    formula: raw.formula,
    systemId: raw.systemId,
    systemZh: sys.nameZh,
    pointGroup: raw.pointGroup,
    habitZh: raw.habitZh,
    twinLawZh: raw.twinLawZh,
    mohs: raw.mohs,
    cleavageZh: raw.cleavageZh,
    opticClass: oa.className,
    opticSign: oa.sign,
    opticSignZh: oa.signLabelZh,
    twoVDeg: oa.twoVDeg,
    riText,
    indices: mat.indices,
    birefringence: oa.deltaN,
    sg: mat.sg,
    opticalActivity: mat.opticalActivity,
    pleochroism: mat.pleochroism,
    pleoColors: mat.pleoColors,
    pleochroismZh: raw.pleochroismZh,
    opticLabel,
    isOpaque: Boolean(raw.isOpaque || mat.opaqueMetallic),
    opaqueMetallic: Boolean(raw.isOpaque || mat.opaqueMetallic),
    inkColor: raw.inkColor,
    rpgQuote: raw.rpgQuote,
    diagnosticTip: raw.diagnosticTip,
  });
}

